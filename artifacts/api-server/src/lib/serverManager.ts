export async function startServer(id: string, memoryMb: number): Promise<void> {
  const proc = processes.get(id);
  if (!proc || proc.status === "running") return;

  proc.status = "starting";
  proc.startedAt = new Date();
  proc.memoryUsed = 0;
  proc.cpuPercent = 0;

  let msgIdx = 0;
  const startupInterval = setInterval(() => {
    if (msgIdx < startupMessages.length) {
      broadcast(proc, startupMessages[msgIdx]);
      msgIdx++;
    } else {
      clearInterval(startupInterval);
      proc.status = "running";
      proc.memoryUsed = Math.floor(memoryMb * 0.45);
      proc.cpuPercent = 5 + Math.random() * 10;
      proc.playerCount = 0;

      const statsInterval = setInterval(() => {
        if (proc.status !== "running") { clearInterval(statsInterval); return; }
        proc.cpuPercent = Math.max(2, Math.min(95, proc.cpuPercent + (Math.random() * 10 - 5)));
        proc.memoryUsed = Math.max(
          Math.floor(memoryMb * 0.3),
          Math.min(Math.floor(memoryMb * 0.85), proc.memoryUsed + Math.floor(Math.random() * 20 - 8))
        );
        proc.networkRx += Math.floor(Math.random() * 5000);
        proc.networkTx += Math.floor(Math.random() * 2000);
      }, 3000);

      const heartbeatInterval = setInterval(() => {
        if (proc.status !== "running") { clearInterval(heartbeatInterval); return; }
        const msgs = [
          "[Server thread/INFO]: Saving the game (this may cause the game to stop for a moment!)",
          "[Server thread/INFO]: Saved the game",
          `[Server thread/INFO]: There are ${proc.playerCount} of a max of 20 players online`,
          "[Server thread/INFO]: [VortexPanel] Heartbeat OK",
        ];
        broadcast(proc, msgs[Math.floor(Math.random() * msgs.length)]);
      }, 30000);

      proc.intervals.push(statsInterval, heartbeatInterval);
    }
  }, 600);

  proc.intervals.push(startupInterval);
}

export async function stopServer(id: string): Promise<void> {
  const proc = processes.get(id);
  if (!proc || proc.status === "stopped") return;

  proc.status = "stopping";
  const msgs = [
    "[Server thread/INFO]: Stopping the server",
    "[Server thread/INFO]: Stopping server",
    "[Server thread/INFO]: Saving players",
    "[Server thread/INFO]: Saving worlds",
    "[Server thread/INFO]: Saving chunks for level 'ServerLevel[world]'/minecraft:overworld",
    "[Server thread/INFO]: ThreadedAnvilChunkStorage: All chunks are saved",
    "[Server thread/INFO]: Flushing profiler...",
  ];

  let i = 0;
  const stopInterval = setInterval(() => {
    if (i < msgs.length) {
      broadcast(proc, msgs[i]);
      i++;
    } else {
      clearInterval(stopInterval);
      for (const iv of proc.intervals) clearInterval(iv);
      proc.intervals = [];
      proc.status = "stopped";
      proc.stoppedAt = new Date();
      proc.memoryUsed = 0;
      proc.cpuPercent = 0;
      proc.playerCount = 0;
    }
  }, 400);

  proc.intervals.push(stopInterval);
}

export async function restartServer(id: string, memoryMb: number): Promise<void> {
  await stopServer(id);
  setTimeout(() => startServer(id, memoryMb), 3000);
}

export async function killServer(id: string): Promise<void> {
  const proc = processes.get(id);
  if (!proc) return;
  for (const iv of proc.intervals) clearInterval(iv);
  proc.intervals = [];
  proc.status = "stopped";
  proc.stoppedAt = new Date();
  proc.memoryUsed = 0;
  proc.cpuPercent = 0;
  proc.playerCount = 0;
  broadcast(proc, "[Server thread/INFO]: Server killed by operator");
}

export async function sendCommand(id: string, command: string): Promise<void> {
  const proc = processes.get(id);
  if (!proc) return;

  broadcast(proc, `> ${command}`);

  if (proc.status !== "running") {
    broadcast(proc, "[ERROR]: Server is not running");
    return;
  }

  const cmd = command.trim().toLowerCase();
  if (cmd === "help") {
    broadcast(proc, "[Server thread/INFO]: --- Showing help page 1 of 12 ---");
    broadcast(proc, "[Server thread/INFO]: /ban <player> [reason]");
    broadcast(proc, "[Server thread/INFO]: /gamemode <mode> [player]");
    broadcast(proc, "[Server thread/INFO]: /give <player> <item> [amount]");
    broadcast(proc, "[Server thread/INFO]: /list -- Shows list of online players");
    broadcast(proc, "[Server thread/INFO]: /op <player> -- Grants op status");
    broadcast(proc, "[Server thread/INFO]: /stop -- Stops the server");
    broadcast(proc, "[Server thread/INFO]: /tp <player1> <player2> -- Teleport");
    broadcast(proc, "[Server thread/INFO]: /whitelist <add|remove|list|on|off|reload>");
  } else if (cmd === "list") {
    broadcast(proc, `[Server thread/INFO]: There are ${proc.playerCount} of a max of 20 players online: ${proc.playerCount > 0 ? "Player1" : ""}`);
  } else if (cmd === "stop") {
    setTimeout(() => stopServer(id), 500);
  } else if (cmd.startsWith("say ")) {
    broadcast(proc, `[Server thread/INFO]: [Server] ${command.substring(4)}`);
  } else if (cmd.startsWith("op ")) {
    broadcast(proc, `[Server thread/INFO]: Opped ${command.substring(3).trim()}`);
  } else if (cmd.startsWith("ban ")) {
    broadcast(proc, `[Server thread/INFO]: Banned player ${command.substring(4).trim().split(" ")[0]}`);
  } else if (cmd === "whitelist list") {
    broadcast(proc, "[Server thread/INFO]: There are 1 whitelisted players: AdminPlayer");
  } else if (cmd === "whitelist on") {
    broadcast(proc, "[Server thread/INFO]: Whitelist is now turned on");
  } else if (cmd === "whitelist off") {
    broadcast(proc, "[Server thread/INFO]: Whitelist is now turned off");
  } else if (cmd === "save-all") {
    broadcast(proc, "[Server thread/INFO]: Saving...");
    setTimeout(() => broadcast(proc, "[Server thread/INFO]: Saved the game"), 800);
  } else if (cmd === "tps") {
    const tps = (18 + Math.random() * 2).toFixed(2);
    broadcast(proc, `[Server thread/INFO]: TPS from last 1m, 5m, 15m: ${tps}, ${tps}, ${tps}`);
  } else if (cmd === "version") {
    broadcast(proc, "[Server thread/INFO]: This server is running Paper version 1.21.1-DEV (MC: 1.21.1)");
  } else if (cmd === "plugins" || cmd === "pl") {
    broadcast(proc, "[Server thread/INFO]: Plugins (3): EssentialsX, WorldGuard, LuckPerms");
  } else {
    broadcast(proc, `[Server thread/WARN]: Unknown or incomplete command, see 'help'`);
  }
}

export function getLogs(id: string, lines = 100): string[] {
  const proc = processes.get(id);
  if (!proc) return [];
  return proc.logs.slice(-lines);
}

export function addClient(id: string, ws: WebSocket): void {
  const proc = processes.get(id);
  if (!proc) return;
  proc.clients.add(ws);
}

export function removeClient(id: string, ws: WebSocket): void {
  const proc = processes.get(id);
  if (!proc) return;
  proc.clients.delete(ws);
}

export function getStats(id: string, diskMb: number, memoryMb: number) {
  const proc = processes.get(id);
  const running = proc?.status === "running";
  return {
    serverId: id,
    cpuPercent: running ? proc!.cpuPercent : 0,
    memoryUsed: running ? proc!.memoryUsed : 0,
    memoryLimit: memoryMb,
    diskUsed: Math.floor(diskMb * 0.38),
    diskLimit: diskMb,
    networkRx: proc?.networkRx ?? 0,
    networkTx: proc?.networkTx ?? 0,
    uptime: running && proc!.startedAt ? Math.floor((Date.now() - proc!.startedAt.getTime()) / 1000) : 0,
    playerCount: proc?.playerCount ?? 0,
  };
}
