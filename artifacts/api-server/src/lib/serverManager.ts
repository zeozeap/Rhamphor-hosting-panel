export function initFileSystem(serverId: string, serverType = "paper"): void {
  if (!fileSystems.has(serverId)) {
    const fs = new Map<string, FileEntry>();
    for (const f of defaultFiles(serverType)) {
      fs.set(f.path, f);
    }
    fileSystems.set(serverId, fs);
  }
}

export function listFiles(serverId: string, dirPath = "/"): FileEntry[] {
  const fs = fileSystems.get(serverId);
  if (!fs) return [];

  const entries: FileEntry[] = [];
  const normalizedDir = dirPath.endsWith("/") && dirPath !== "/" ? dirPath.slice(0, -1) : dirPath;

  for (const [path, entry] of fs.entries()) {
    if (path === normalizedDir) continue;
    const withoutDir = path.startsWith(normalizedDir === "/" ? "" : normalizedDir)
      ? path.substring(normalizedDir === "/" ? 0 : normalizedDir.length)
      : null;
    if (!withoutDir) continue;
    const parts = withoutDir.replace(/^\//, "").split("/");
    if (parts.length === 1 && normalizedDir === "/") {
      entries.push(entry);
    } else if (parts.length === 1 && normalizedDir !== "/") {
      entries.push(entry);
    } else if (parts.length === 2 && normalizedDir !== "/" && parts[0] === "") {
      entries.push(entry);
    }
  }

  return entries.sort((a, b) => {
    if (a.isDir !== b.isDir) return a.isDir ? -1 : 1;
    return a.name.localeCompare(b.name);
  });
}

export function readFile(serverId: string, filePath: string): FileEntry | null {
  const fs = fileSystems.get(serverId);
  if (!fs) return null;
  return fs.get(filePath) ?? null;
}

export function writeFile(serverId: string, filePath: string, content: string): FileEntry {
  let fs = fileSystems.get(serverId);
  if (!fs) {
    fs = new Map();
    fileSystems.set(serverId, fs);
  }

  const name = filePath.split("/").filter(Boolean).pop() ?? filePath;
  const entry: FileEntry = {
    name,
    path: filePath,
    isDir: false,
    content,
    size: Buffer.byteLength(content, "utf8"),
    updatedAt: new Date().toISOString(),
  };
  fs.set(filePath, entry);
  return entry;
}

export function deleteFilePath(serverId: string, filePath: string): boolean {
  const fs = fileSystems.get(serverId);
  if (!fs) return false;

  const entry = fs.get(filePath);
  if (!entry) return false;

  fs.delete(filePath);

  if (entry.isDir) {
    const prefix = filePath.endsWith("/") ? filePath : filePath + "/";
    for (const path of Array.from(fs.keys())) {
      if (path.startsWith(prefix)) {
        fs.delete(path);
      }
    }
  }

  return true;
}

